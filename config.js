/*
   Определяют на каком расстоянии от идеального диапазона
   начинается каждый следующий tier.
   
   Единица измерения: halfRange (половина ширины идеального диапазона).
   
   Логика:
   - center = (lo + hi) / 2
   - halfRange = (hi - lo) / 2
   - deviation = |value - center|
   
   deviation <= halfRange × threshold[0] → T1 (идеал)
   deviation <= halfRange × threshold[1] → T2
   deviation <= halfRange × threshold[2] → T3
   deviation <= halfRange × threshold[3] → T4
   иначе                                    → T5 (экстремум)
*/

