/* ==================== ПРОВЕРКА ЦЕЛОСТНОСТИ ==================== */
(function validatePoints() {
  const seen = new Set();
  for (const p of POINTS) {
    if (!p.id || !p.name || !p.hint || !p.instruction) {
      console.error('points.js: точка без обязательных полей:', p);
    }
    if (typeof p.exampleX !== 'number' || typeof p.exampleY !== 'number') {
      console.error('points.js: точка без exampleX/exampleY:', p.id);
    }
    if (seen.has(p.id)) {
      console.error('points.js: дублирующийся id:', p.id);
    }
    seen.add(p.id);
  }
  console.log(`points.js: загружено ${POINTS.length} точек`);
})();

const POINTS_BY_ID = Object.fromEntries(POINTS.map(p => [p.id, p]));
