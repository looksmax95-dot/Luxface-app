/* =====================================================================
   FaceMetrics — TG Mini App: оценка геометрии лица (32 метрики, без нейросетей)
   МОДУЛЬ 1/8: js/points.js
   ---------------------------------------------------------------------
   Назначение:
     • реестр из 34 анатомических точек (landmarks) с русскими гайдами;
     • 7 этапов поэтапной разметки (порядок = порядок постановки);
     • правила валидации разметки (симметрия, порядки осей, «между»);
     • линии для экрана обзора (review).
   Соглашения:
     • Координаты точек — в пикселях ИЗОБРАЖЕНИЯ (не экрана), ось Y вниз.
     • Суффикс _L = ЛЕВАЯ СТОРОНА ФОТО, _R = правая сторона фото.
       (Если селфи зеркальное — не важно: все метрики симметричны.)
     • Модуль не трогает DOM и не имеет зависимостей: грузится обычным
       <script>, публикует глобал FM.points. ES-модули не используем,
       чтобы работало и через file:// при тестах с телефона.
   ===================================================================== */
(function (global) {
  'use strict';

  const FM = (global.FM = global.FM || {});

  /* -----------------------------------------------------------------
     1. РЕЕСТР ТОЧЕК
        zoom  — рекомендуемый масштаб прицела при постановке (1 = всё лицо);
        side  — 'L' | 'R' | 'C' (сторона фото / центр).
     ----------------------------------------------------------------- */
  const POINTS = {};
  function pt(id, name, guide, zoom, side) {
    POINTS[id] = { id: id, name: name, guide: guide, zoom: zoom, side: side || 'C' };
  }

  /* --- Этап 1: осевая линия (сверху вниз) --- */
  pt('TR', 'Линия роста волос (трихион)',
    'Центр лба: граница кожи и волос строго по вертикали лица. Волосы должны быть убраны.', 1.3, 'C');
  pt('GL', 'Нижний край бровей (глабелла)',
    'Точка между бровями на вертикали лица: самый нижний край волосков бровей по центру.', 1.6, 'C');
  pt('N',  'Переносица (назион)',
    'Самая глубокая точка впадины между глазами — там, где начинается спинка носа.', 2.0, 'C');
  pt('SN', 'Основание носа (субназале)',
    'Центр под носом: где перегородка носа (колумелла) соединяется с верхней губой.', 2.0, 'C');
  pt('GN', 'Низ подбородка (гнатион)',
    'Самая нижняя точка подбородка строго по центру лица.', 1.6, 'C');

  /* --- Этап 2: скулы и виски (край силуэта) --- */
  pt('ZY_L', 'Скула слева (зигион)',
    'Самая широкая точка скуловой дуги: веди прицел по внешнему краю силуэта лица на уровне скул.', 1.5, 'L');
  pt('ZY_R', 'Скула справа (зигион)',
    'Зеркально: самая широкая точка скуловой дуги справа по краю силуэта.', 1.5, 'R');
  pt('BT_L', 'Висок слева',
    'Самая широкая точка контура лба/виска НАД скулой, край силуэта.', 1.5, 'L');
  pt('BT_R', 'Висок справа',
    'Зеркально: самая широкая точка контура лба/виска над скулой справа.', 1.5, 'R');

  /* --- Этап 3: челюсть и шея --- */
  pt('JW_L', 'Ширина челюсти слева',
    'Самая широкая точка нижней трети силуэта: массив челюсти с жевательной мышцей, ниже скулы.', 1.5, 'L');
  pt('JW_R', 'Ширина челюсти справа',
    'Зеркально: самая широкая точка нижней трети силуэта справа.', 1.5, 'R');
  pt('GO_L', 'Угол челюсти слева (гонион)',
    'Точка излома контура: где линия низа челюсти поворачивает вверх к уху.', 2.0, 'L');
  pt('GO_R', 'Угол челюсти справа (гонион)',
    'Зеркально: точка излома контура челюсти справа, поворот вверх к уху.', 2.0, 'R');
  pt('NK_L', 'Шея слева',
    'Самая широкая точка контура шеи на уровне угла челюсти или чуть ниже.', 1.5, 'L');
  pt('NK_R', 'Шея справа',
    'Зеркально: самая широкая точка контура шеи справа.', 1.5, 'R');

  /* --- Этап 4: уголки глаз --- */
  pt('EN_L', 'Внутренний уголок глаза слева',
    'Точка слёзного озера у переносицы. Зум максимум, ставь точно в стык век.', 3.2, 'L');
  pt('EX_L', 'Внешний уголок глаза слева',
    'Внешняя точка смыкания век у виска. Зум максимум.', 3.2, 'L');
  pt('EN_R', 'Внутренний уголок глаза справа',
    'Зеркально: слёзное озеро у переносицы справа. Зум максимум.', 3.2, 'R');
  pt('EX_R', 'Внешний уголок глаза справа',
    'Зеркально: внешняя точка смыкания век справа. Зум максимум.', 3.2, 'R');

  /* --- Этап 5: веки --- */
  pt('UL_L', 'Середина верхнего века слева',
    'Самая верхняя точка ресничного края левого глаза, строго посередине между уголками.', 3.6, 'L');
  pt('LL_L', 'Середина нижнего века слева',
    'Самая нижняя точка края нижнего века левого глаза, посередине между уголками.', 3.6, 'L');
  pt('UL_R', 'Середина верхнего века справа',
    'Зеркально: верхняя точка ресничного края правого глаза посередине.', 3.6, 'R');
  pt('LL_R', 'Середина нижнего века справа',
    'Зеркально: нижняя точка края нижнего века правого глаза посередине.', 3.6, 'R');

  /* --- Этап 6: брови --- */
  pt('BR_IN_L', 'Начало брови слева',
    'Внутренний кончик волосков брови (головка брови).', 2.6, 'L');
  pt('BR_OUT_L', 'Кончик брови слева',
    'Самая внешняя точка хвоста брови слева.', 2.6, 'L');
  pt('BR_IN_R', 'Начало брови справа',
    'Зеркально: внутренний кончик волосков брови справа.', 2.6, 'R');
  pt('BR_OUT_R', 'Кончик брови справа',
    'Зеркально: самая внешняя точка хвоста брови справа.', 2.6, 'R');

  /* --- Этап 7: нос и рот --- */
  pt('AL_L', 'Крыло носа слева',
    'Самая широкая точка контура ноздри слева (alar point).', 2.4, 'L');
  pt('AL_R', 'Крыло носа справа',
    'Зеркально: самая широкая точка контура ноздри справа.', 2.4, 'R');
  pt('LS', 'Верх верхней губы',
    'Центр верхней кромки верхней губы: середина дуги Купидона, конец филтрума.', 2.6, 'C');
  pt('ST', 'Линия смыкания губ (стомион)',
    'Центр щели между губами: где верхняя губа касается нижней.', 2.6, 'C');
  pt('LI', 'Низ нижней губы',
    'Центр нижней кромки нижней губы, где кожа переходит в подбородок.', 2.6, 'C');
  pt('CH_L', 'Уголок рта слева',
    'Точка смыкания губ в левом углу рта (комиссура).', 2.6, 'L');
  pt('CH_R', 'Уголок рта справа',
    'Зеркально: точка смыкания губ в правом углу рта.', 2.6, 'R');

  /* -----------------------------------------------------------------
     2. ЭТАПЫ РАЗМЕТКИ (порядок точек внутри этапа = порядок постановки)
     ----------------------------------------------------------------- */
  const STAGES = [
    { id: 1, title: 'Осевая линия',   caption: '5 точек сверху вниз по центру лица',
      points: ['TR', 'GL', 'N', 'SN', 'GN'] },
    { id: 2, title: 'Скулы и виски',  caption: '4 точки по внешнему краю силуэта',
      points: ['ZY_L', 'ZY_R', 'BT_L', 'BT_R'] },
    { id: 3, title: 'Челюсть и шея',  caption: '6 точек нижнего силуэта',
      points: ['JW_L', 'JW_R', 'GO_L', 'GO_R', 'NK_L', 'NK_R'] },
    { id: 4, title: 'Уголки глаз',    caption: '4 точки, максимальный зум',
      points: ['EN_L', 'EX_L', 'EN_R', 'EX_R'] },
    { id: 5, title: 'Веки',           caption: '4 точки: середины краёв век',
      points: ['UL_L', 'LL_L', 'UL_R', 'LL_R'] },
    { id: 6, title: 'Брови',          caption: '4 точки: головка и хвост',
      points: ['BR_IN_L', 'BR_OUT_L', 'BR_IN_R', 'BR_OUT_R'] },
    { id: 7, title: 'Нос и рот',      caption: '7 точек: крылья носа и контур губ',
      points: ['AL_L', 'AL_R', 'LS', 'ST', 'LI', 'CH_L', 'CH_R'] }
  ];

  /* Плоский порядок постановки всех точек */
  const ORDER = STAGES.reduce(function (acc, s) { return acc.concat(s.points); }, []);

  /* -----------------------------------------------------------------
     3. СЛУЖЕБНЫЕ ЗАПРОСЫ
     ----------------------------------------------------------------- */
  function stageOf(id) {
    for (let i = 0; i < STAGES.length; i++) {
      if (STAGES[i].points.indexOf(id) !== -1) return STAGES[i];
    }
    return null;
  }
  function indexInStage(id) {
    const s = stageOf(id);
    return s ? s.points.indexOf(id) : -1;
  }
  function indexOf(id) { return ORDER.indexOf(id); }
  function pairOf(id) {
    if (/_L$/.test(id)) return id.replace(/_L$/, '_R');
    if (/_R$/.test(id)) return id.replace(/_R$/, '_L');
    return null;
  }

  /* -----------------------------------------------------------------
     4. ПРАВИЛА ВАЛИДАЦИИ РАЗМЕТКИ
        Возвращаем массив предупреждений {code, ids, msg} — НЕ ошибки,
        а подсказки «проверь точку». Вызывается на экране обзора.
     ----------------------------------------------------------------- */
  const SYM_PAIRS = [           /* зеркальные пары: сверяем уровень Y   */
    ['ZY_L', 'ZY_R'], ['BT_L', 'BT_R'], ['JW_L', 'JW_R'], ['GO_L', 'GO_R'],
    ['NK_L', 'NK_R'], ['EN_L', 'EN_R'], ['EX_L', 'EX_R'], ['UL_L', 'UL_R'],
    ['LL_L', 'LL_R'], ['BR_IN_L', 'BR_IN_R'], ['BR_OUT_L', 'BR_OUT_R'],
    ['AL_L', 'AL_R'], ['CH_L', 'CH_R']
  ];
  const YORDERS = [             /* сверху вниз по Y                     */
    ['TR', 'GL', 'N', 'SN', 'GN'],
    ['LS', 'ST', 'LI']
  ];
  const XORDERS = [             /* слева направо по X                   */
    ['EX_L', 'EN_L', 'EN_R', 'EX_R'],
    ['CH_L', 'AL_L', 'AL_R', 'CH_R']
  ];
  const BETWEEN_X = [           /* точка B по X строго между A и C      */
    ['UL_L', 'EX_L', 'EN_L'], ['LL_L', 'EX_L', 'EN_L'],
    ['UL_R', 'EN_R', 'EX_R'], ['LL_R', 'EN_R', 'EX_R']
  ];
  const MIDLINE = ['TR', 'GL', 'N', 'SN', 'GN', 'LS', 'ST', 'LI'];

  function has(pts, id) {
    return !!pts[id] && isFinite(pts[id].x) && isFinite(pts[id].y);
  }
  function need(pts, ids) {
    return ids.every(function (id) { return has(pts, id); });
  }

  function validate(pts) {
    const warns = [];
    if (!need(pts, ['TR', 'GN'])) return warns;               /* без оси нечего проверять */
    const faceH = Math.abs(pts.GN.y - pts.TR.y) || 1;
    const tolY = faceH * 0.04;                                /* 4% высоты лица */
    const pct = function (d) { return Math.round((d / faceH) * 100); };

    SYM_PAIRS.forEach(function (pr) {
      if (!need(pts, pr)) return;
      const d = Math.abs(pts[pr[0]].y - pts[pr[1]].y);
      if (d > tolY) {
        warns.push({
          code: 'SYM_Y', ids: pr,
          msg: POINTS[pr[0]].name + ' и ' + POINTS[pr[1]].name +
               ': расхождение по высоте ' + pct(d) + '% лица. Голова наклонена или точка сбита.'
        });
      }
    });

    YORDERS.forEach(function (chain) {
      if (!need(pts, chain)) return;
      for (let i = 1; i < chain.length; i++) {
        const d = pts[chain[i]].y - pts[chain[i - 1]].y;
        if (d < -faceH * 0.01) {
          warns.push({
            code: 'Y_ORDER', ids: [chain[i - 1], chain[i]],
            msg: POINTS[chain[i]].name + ' оказалась ВЫШЕ ' + POINTS[chain[i - 1]].name +
                 ' — проверь обе точки.'
          });
        }
      }
    });

    XORDERS.forEach(function (chain) {
      if (!need(pts, chain)) return;
      for (let i = 1; i < chain.length; i++) {
        if (pts[chain[i]].x <= pts[chain[i - 1]].x) {
          warns.push({
            code: 'X_ORDER', ids: [chain[i - 1], chain[i]],
            msg: POINTS[chain[i]].name + ' должна быть правее ' + POINTS[chain[i - 1]].name + '.'
          });
        }
      }
    });

    BETWEEN_X.forEach(function (tr) {
      if (!need(pts, tr)) return;
      const a = Math.min(pts[tr[1]].x, pts[tr[2]].x);
      const b = Math.max(pts[tr[1]].x, pts[tr[2]].x);
      const x = pts[tr[0]].x;
      if (x < a || x > b) {
        warns.push({
          code: 'BETWEEN_X', ids: tr,
          msg: POINTS[tr[0]].name + ' вышла за границы уголков глаза — уточни положение.'
        });
      }
    });

    if (need(pts, ['EN_L', 'EN_R'])) {
      const lo = pts.EN_L.x, hi = pts.EN_R.x;
      MIDLINE.forEach(function (id) {
        if (!has(pts, id)) return;
        if (pts[id].x < lo || pts[id].x > hi) {
          warns.push({
            code: 'MIDLINE', ids: [id],
            msg: POINTS[id].name + ' ушла с вертикали лица (вне зоны между внутренними уголками глаз).'
          });
        }
      });
    }
    return warns;
  }

  /* -----------------------------------------------------------------
     5. ЛИНИИ ДЛЯ ЭКРАНА ОБЗОРА (визуальная самопроверка пользователем)
     ----------------------------------------------------------------- */
  const REVIEW_LINES = [
    ['ZY_L', 'ZY_R'], ['BT_L', 'BT_R'], ['JW_L', 'JW_R'], ['GO_L', 'GO_R'], ['NK_L', 'NK_R'],
    ['TR', 'GN'], ['EX_L', 'EX_R'], ['EN_L', 'EN_R'],
    ['EN_L', 'EX_L'], ['EN_R', 'EX_R'], ['UL_L', 'LL_L'], ['UL_R', 'LL_R'],
    ['BR_IN_L', 'BR_OUT_L'], ['BR_IN_R', 'BR_OUT_R'],
    ['AL_L', 'AL_R'], ['CH_L', 'CH_R'], ['LS', 'LI'], ['N', 'SN'], ['SN', 'GN'],
    ['GO_L', 'GN'], ['GO_R', 'GN']
  ];

  /* -----------------------------------------------------------------
     6. ПУБЛИЧНЫЙ API МОДУЛЯ
     ----------------------------------------------------------------- */
  FM.points = {
    POINTS: POINTS,
    STAGES: STAGES,
    ORDER: ORDER,
    REVIEW_LINES: REVIEW_LINES,
    total: ORDER.length,                 /* 34 */
    totalStages: STAGES.length,          /* 7  */
    stageOf: stageOf,
    indexInStage: indexInStage,
    indexOf: indexOf,
    pairOf: pairOf,
    validate: validate
  };
})(typeof window !== 'undefined' ? window : this);
